const CONTRACT_KEYS: ReadonlySet<string> = new Set<string>(UI_ROUTE_KEYS);
const MCP_KEYS: readonly string[] = (["GET", "POST", "DELETE"] as const).map((method) => `${method} ${MCP_PATH}`);
const AUDIT_TYPE_SET: ReadonlySet<string> = new Set<string>(AUDIT_EVENT_TYPES);
const AUDIT_BACKLOG = 200;
const NEW_LINK_MIN_GAP_MS = 5_000;

// Header names a module or an upstream Response may not set. Cookies and CORS approval are never emitted;
// the security headers are fixed; framing headers belong to Node.
const FORBIDDEN_RESPONSE_HEADERS = /^(?:set-cookie2?|access-control-.*|content-security-policy.*|cross-origin-.*|x-frame-options|x-content-type-options|referrer-policy|permissions-policy|content-length|transfer-encoding|connection|keep-alive|upgrade|trailer|content-encoding)$/i;

const SECURITY: Readonly<Record<string, string>> = Object.freeze({
  ...Object.fromEntries(securityHeaders("cockpit").map((pair) => [pair.key, pair.value])),
  "Cache-Control": "no-store",
});

interface Bucket {
  tokens: number;
  at: number;
}

function stripHeaders(extra: Readonly<Record<string, string>> | undefined): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, value] of Object.entries(extra ?? {})) {
    if (!FORBIDDEN_RESPONSE_HEADERS.test(name) && typeof value === "string" && !/[\r\n]/.test(value)) out[name] = value;
  }
  return out;
}

function sanitisedHeaders(req: IncomingMessage): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, value] of Object.entries(req.headers)) {
    if (typeof value !== "string") continue;
    if (name === "authorization" || name === "cookie" || name === "cookie2") continue;
    out[name] = value;
  }
  return out;
}

function matchPath(route: RegisteredRoute, path: string): { readonly params: Record<string, string>; readonly rest: string } | undefined {
  if (route.path.endsWith("/")) return path.startsWith(route.path) && path.length > route.path.length ? { params: {}, rest: path.slice(route.path.length) } : undefined;
  if (!route.path.includes(":")) return path === route.path ? { params: {}, rest: "" } : undefined;
  const want = route.path.split("/");
  const got = path.split("/");
  if (want.length !== got.length) return undefined;
  const params: Record<string, string> = {};
  for (let index = 0; index < want.length; index += 1) {
    const expected = want[index];
    const actual = got[index];
    if (expected === undefined || actual === undefined) return undefined;
    if (expected.startsWith(":")) {
      if (actual === "") return undefined;
      params[expected.slice(1)] = actual;
    } else if (expected !== actual) {
      return undefined;
    }
  }
  return { params, rest: "" };
}

// exact routes first, then patterns, then prefixes.
function specificity(route: RegisteredRoute): number {
  return route.path.endsWith("/") ? 2 : route.path.includes(":") ? 1 : 0;
}

export function isApiPath(path: string): boolean {
  return path === MCP_PATH || path.startsWith("/ui/") || path === "/ui";
}

// ---- the pairing route (the only public route) ---------------------------------------------------------------------------

const pairBodySchema = z.object({ code: z.string().max(200) }).strict();

function pairRoute(auth: Auth, host: () => DaemonHost): RegisteredRoute {
  return defineRoute({
    method: "POST",
    path: "/ui/pair",
    access: "public",
    body: pairBodySchema,
    handler: (ctx) => {
      const daemon = host();
      const code = ctx.body.code;
      if (!pairCodeSchema.safeParse(code).success) {
        daemon.emitAudit({ ev: "ui.pair", outcome: "refused", code: "pairing_invalid" });
        return fail("pairing_invalid", "The pairing code is wrong or was already used. Reload the page for a new link.");
      }
      const result = auth.redeemPairing(code);
      if (!result.ok) {
        const expired = result.reason === "expired";
        daemon.emitAudit({ ev: "ui.pair", outcome: "refused", code: expired ? "pairing_expired" : "pairing_invalid" });
        return expired
          ? fail("pairing_expired", "The pairing code ran out of time. Reload the page for a new link.")
          : fail("pairing_invalid", "The pairing code is wrong or was already used. Reload the page for a new link.");
      }
      daemon.emitAudit({ ev: "ui.pair", outcome: "ok", tokenId: result.principal.id });
      const scopes = effectiveScopes(["read", "prepare"], daemon.instance());
      return json({ token: result.token, kind: "ui", scopes });
    },
  });
}

// ---- startDaemon ---------------------------------------------------------------------------------------------------------------

export async function startDaemon(options: DaemonOptions): Promise<Daemon> {
  const clock = options.clock ?? Date.now;
  const random = options.random ?? defaultRandom;
  const auth = options.auth;
  const maxBody = options.maxBodyBytes ?? MAX_REQUEST_BODY_BYTES;
  const perSecond = options.requestsPerSecond ?? 100;
  const burst = perSecond * 2.5;

  const routes: RegisteredRoute[] = [];
  const guards: Guard[] = [];
  const closers: (() => void | Promise<void>)[] = [];
  const moduleClosers: { readonly name: string; readonly close: () => void | Promise<void> }[] = [];
  const auditListeners = new Set<AuditListener>();
  const auditBacklog: DaemonAuditRecord[] = [];
  const buckets = new Map<string, Bucket>();
  const counters = new Map<string, number>();
  const streams = new Set<{ end(): void }>();
  const sockets = new Set<Socket>();
  const shutdown = new AbortController();
  let ready = false;
  let closing: Promise<void> | undefined;
  let lastLinkAt = -Infinity;
  let portValue = 0;
  let hostRef: DaemonHost | undefined;

  const count = (name: string): void => {
    counters.set(name, (counters.get(name) ?? 0) + 1);
  };

  const getHost = (): DaemonHost => {
    if (hostRef === undefined) throw new Error("The daemon host is not ready.");
    return hostRef;
  };

  function registerRoute(route: RegisteredRoute, owner: string): void {
    const allowed = CONTRACT_KEYS.has(route.key) || MCP_KEYS.includes(route.key) || (options.extraRouteKeys ?? []).includes(route.key);
    if (!allowed) throw new DaemonStartError("route_invalid", `Route ${route.key} is not in the frozen contract (bridge/contract.ts UI_ROUTE_KEYS).`, owner);
    if (routes.some((existing) => existing.key === route.key)) throw new DaemonStartError("route_invalid", `Route ${route.key} is registered twice.`, owner);
    if (route.access !== "public" && (typeof route.access !== "object" || !(["read", "prepare", "submit"] as readonly string[]).includes(route.access.scope))) {
      throw new DaemonStartError("route_invalid", `Route ${route.key} has no valid access rule.`, owner);
    }
    if (route.method === "POST" && route.body === undefined) throw new DaemonStartError("route_invalid", `POST route ${route.key} must declare its body.`, owner);
    if (route.method !== "POST" && route.body !== undefined) throw new DaemonStartError("route_invalid", `Only POST routes take a body (${route.key}).`, owner);
    routes.push(route);
    routes.sort((a, b) => specificity(a) - specificity(b));
  }

  const host: DaemonHost = {
    version: options.version,
    get port() {
      return portValue;
    },
    get origin() {
      return expectedOrigin(portValue);
    },
    env: options.env ?? {},
    stderr: options.stderr,
    clock,
    random,
    instance: () => auth.instance(),
    dataDir: () => options.dataDir?.() ?? null,
    engageKill: async (reason) => {
      try {
        return (await options.engageKill?.(reason)) ?? false;
      } catch {
        return false;
      }
    },
    addGuard: (guard) => {
      guards.push(guard);
    },
    emitAudit: (record) => {
      if (!AUDIT_TYPE_SET.has(record.ev)) return;
      if (auditListeners.size === 0) {
        auditBacklog.push(record);
        if (auditBacklog.length > AUDIT_BACKLOG) auditBacklog.shift();
        return;
      }
      for (const listener of auditListeners) {
        try {
          listener(record);
        } catch {
          // An audit sink must not break a request; the adapter reports its own health.
        }
      }
    },
    onAudit: (listener, opts) => {
      auditListeners.add(listener);
      if (opts?.replay === true) {
        for (const record of auditBacklog.splice(0)) {
          try {
            listener(record);
          } catch {
            // see emitAudit
          }
        }
      }
      return () => {
        auditListeners.delete(listener);
      };
    },
    onClose: (callback) => {
      closers.push(callback);
    },
    scopesFor: (ceiling) => effectiveScopes(ceiling, auth.instance()),
    auth: {
      get agentScopes() {
        return auth.agentScopes;
      },
      hasAgentToken: () => auth.hasAgentToken(),
    },
    routes: () => routes.map((route) => ({ key: route.key, access: route.access })),
    openStreams: () => streams.size,
    stats: () => Object.fromEntries(counters),
  };
  hostRef = host;
  registerRoute(pairRoute(auth, getHost), "daemon");

  // ---- reply helpers ----

  function writeHead(res: ServerResponse, status: number, extra?: Readonly<Record<string, string>>): void {
    res.statusCode = status;
    for (const [name, value] of Object.entries({ ...stripHeaders(extra), ...SECURITY })) res.setHeader(name, value);
  }

  // Sockets that already carry a complete answer with `Connection: close`.
  const answeredAndClosing = new WeakSet<object>();

  function replyJson(res: ServerResponse, status: number, body: unknown, extra?: Readonly<Record<string, string>>, closeAfter = false): void {
    let text: string;
    try {
      text = JSON.stringify(body);
    } catch {
      text = JSON.stringify(errorBody({ code: "internal", message: "The answer could not be encoded." }));
      status = 500;
    }
    writeHead(res, status, { "Content-Type": "application/json; charset=utf-8", ...extra });
    res.setHeader("Content-Length", Buffer.byteLength(text));
    if (closeAfter) {
      res.setHeader("Connection", "close");
      // The body of this request was not read. Whatever the client sends next is not a new request, and the
      // parser's complaint about it must not become a second response on this socket (see clientError below).
      if (res.socket !== null) answeredAndClosing.add(res.socket);
    }
    res.end(text);
  }

  function replyFailure(res: ServerResponse, failure: FailureBody, closeAfter = false): void {
    count(failure.code);
    // `Connection: close` when the body was not read: it must not leave bytes on a kept-alive socket.
    replyJson(res, BRIDGE_ERROR_HTTP_STATUS[failure.code], errorBody(failure), failure.retryAfterS === undefined ? undefined : { "Retry-After": String(Math.floor(failure.retryAfterS)) }, closeAfter);
  }

  // Fixed texts. They name the daemon's own address (anyone who can connect already knows it) so a user who
  // typed `localhost` is told what to open instead.
  const failures = {
    host: () => ({ code: "host_forbidden", message: `This request's Host is not the daemon's own address. Open ${expectedOrigin(portValue)}/ instead.` }) satisfies FailureBody,
    origin: () => ({ code: "origin_forbidden", message: "This request comes from another origin." }) satisfies FailureBody,
    unauthorized: () => ({ code: "unauthorized", message: "A valid bearer token is required." }) satisfies FailureBody,
    malformed: () => ({ code: "invalid_request", message: "The request could not be understood." }) satisfies FailureBody,
  } as const;

  // ---- the request handler ----

  function allow(principalId: string): number | undefined {
    const now = clock();
    const bucket = buckets.get(principalId) ?? { tokens: burst, at: now };
    bucket.tokens = Math.min(burst, bucket.tokens + ((now - bucket.at) / 1000) * perSecond);
    bucket.at = now;
    if (bucket.tokens < 1) {
      buckets.set(principalId, bucket);
      return Math.max(1, Math.ceil((1 - bucket.tokens) / perSecond));
    }
    bucket.tokens -= 1;
    buckets.set(principalId, bucket);
    return undefined;
  }

  async function readBody(req: IncomingMessage): Promise<Buffer | "too_large" | "aborted"> {
    const chunks: Buffer[] = [];
    let size = 0;
    try {
      for await (const chunk of req) {
        const buffer = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk as Uint8Array);
        size += buffer.length;
        if (size > maxBody) return "too_large";
        chunks.push(buffer);
      }
    } catch {
      return "aborted";
    }
    return Buffer.concat(chunks, size);
  }

  function announce(force: boolean): string | undefined {
    const now = clock();
    if (!force && (auth.pairingOpen() || now - lastLinkAt < NEW_LINK_MIN_GAP_MS)) return undefined;
    lastLinkAt = now;
    const grant = auth.issuePairing();
    const link = `${expectedOrigin(portValue)}/#pair=${grant.code}`;
    // stderr only: the fragment is the secret. It is shown here and nowhere else.
    options.stderr.write(`xo-market cockpit: open this link in your browser to pair it (valid ${PAIR_CODE_TTL_S} s, works once):\n  ${link}\n`);
    return link;
  }

  async function handleStatic(req: IncomingMessage, res: ServerResponse, path: string, method: string, headers: Record<string, string>): Promise<void> {
    if (method !== "GET" && method !== "HEAD") {
      res.setHeader("Allow", "GET, HEAD");
      return replyFailure(res, { code: "method_not_allowed", message: "Only GET and HEAD are served here." }, true);
    }
    if (options.site === undefined) return replyFailure(res, { code: "not_found", message: "Not found." });
    const outcome = await options.site.serve({ method, path, accept: headers["accept"] });
    if (outcome.kind === "refused") return replyFailure(res, { code: outcome.reason === "bad_path" ? "invalid_request" : "not_found", message: outcome.reason === "bad_path" ? "That path is not valid." : "Not found." });
    if (outcome.kind === "missing") {
      return replyFailure(res, {
        code: "not_found",
        message: outcome.reason === "not_built" ? "The Cockpit app is not built. Run: pnpm --dir app run build:cockpit" : "Not found.",
      });
    }
    // The client may have left while serve() was opening the file. Its response 'close' has already fired, so the
    // listener below would never run and the handle would stay open until garbage collection (DS-1). Check first:
    // nothing awaits between this check and the listener, so no close can fall in the gap.
    if (res.destroyed || res.writableEnded || res.socket === null || res.socket.destroyed) {
      outcome.body?.destroy();
      void outcome.close();
      return;
    }
    if (outcome.isIndex && isUserNavigation(headers)) announce(false);
    writeHead(res, 200, { "Content-Type": outcome.contentType });
    res.setHeader("Content-Length", outcome.size);
    if (outcome.body === undefined) {
      res.end();
      return;
    }
    const body = outcome.body;
    res.once("close", () => {
      body.destroy();
      void outcome.close();
    });
    body.on("error", () => res.destroy());
    body.pipe(res);
  }

  async function sendResult(res: ServerResponse, result: RouteResult, requestSignal: AbortController): Promise<void> {
    if (result.kind === "json") return replyJson(res, result.status, result.body, result.headers);
    if (result.kind === "web") {
      const response = result.response;
      writeHead(res, response.status, Object.fromEntries([...response.headers.entries()]));
      if (response.body === null) return void res.end();
      const body = Readable.fromWeb(response.body as import("node:stream/web").ReadableStream);
      res.once("close", () => {
        requestSignal.abort();
        body.destroy();
      });
      body.on("error", () => res.destroy());
      body.pipe(res);
      return;
    }
    writeHead(res, result.status ?? 200, { "Content-Type": result.contentType, "X-Accel-Buffering": "no" });
    res.flushHeaders();
    res.socket?.setNoDelay(true);
    res.socket?.setTimeout(0);
    let closed = false;
    const closeCallbacks: (() => void)[] = [];
    const drainCallbacks: (() => void)[] = [];
    const handle = { end: () => finish() };
    const finish = (): void => {
      if (closed) return;
      closed = true;
      streams.delete(handle);
      for (const callback of closeCallbacks.splice(0)) {
        try {
          callback();
        } catch {
          // a module's cleanup must not stop the others
        }
      }
      if (!res.writableEnded) res.end();
    };
    const sink: StreamSink = {
      write: (chunk) => (closed ? false : res.write(chunk)),
      onDrain: (callback) => {
        drainCallbacks.push(callback);
      },
      onClose: (callback) => {
        if (closed) callback();
        else closeCallbacks.push(callback);
      },
      end: finish,
      get closed() {
        return closed;
      },
    };
    streams.add(handle);
    res.on("drain", () => {
      for (const callback of drainCallbacks.splice(0)) callback();
    });
    res.once("close", () => {
      requestSignal.abort();
      finish();
    });
    try {
      await result.start(sink);
    } catch {
      finish();
    }
  }

  async function handle(req: IncomingMessage, res: ServerResponse): Promise<void> {
    count("requests");
    const method = req.method ?? "";
    const target = parseTarget(req.url ?? "");
    if (target === undefined) return replyFailure(res, failures.malformed(), true);
    if (duplicatedHeader(req.rawHeaders) !== undefined) {
      return replyFailure(res, duplicatedHeader(req.rawHeaders) === "host" ? failures.host() : failures.malformed(), true);
    }
    if (!checkHost(req.headers.host, portValue)) return replyFailure(res, failures.host(), true);
    const originVerdict = checkOrigin(req.headers.origin, portValue);
    if (originVerdict === "bad") return replyFailure(res, failures.origin(), true);

    const headers = sanitisedHeaders(req);
    const api = isApiPath(target.path);
    if (!api) return handleStatic(req, res, target.path, method, headers);

    if (!checkFetchSite(req.headers["sec-fetch-site"] as string | undefined)) return replyFailure(res, failures.origin(), true);
    if (method !== "GET" && method !== "POST" && method !== "DELETE") {
      res.setHeader("Allow", "GET, POST, DELETE");
      return replyFailure(res, { code: "method_not_allowed", message: "That method is not allowed." }, true);
    }
    if (!ready) return replyFailure(res, { code: "precondition_failed", message: "The daemon is still starting." }, true);

    const matches = routes.filter((route) => matchPath(route, target.path) !== undefined);
    const route = matches.find((candidate) => candidate.method === method);

    // Authentication comes before anything that reveals which routes exist.
    const principal = auth.authenticate(req.headers.authorization);
    const isPublic = route?.access === "public";
    if (!isPublic && principal === undefined) {
      if (parseBearer(req.headers.authorization) === undefined && req.headers.authorization !== undefined) count("bad_authorization_header");
      return replyFailure(res, failures.unauthorized(), true);
    }
    if (route === undefined) {
      if (matches.length > 0) return replyFailure(res, { code: "method_not_allowed", message: "That method is not allowed for this route." }, true);
      return replyFailure(res, { code: "not_found", message: "Not found." }, true);
    }
    if (route.access !== "public") {
      if (principal === undefined || !route.kinds.includes(principal.kind) || !principal.scopes.includes(route.access.scope)) {
        return replyFailure(res, { code: "scope_denied", message: "This token may not use this route." }, true);
      }
      const wait = allow(`${principal.kind}:${principal.id}`);
      if (wait !== undefined) return replyFailure(res, { code: "rate_limited", message: "Too many requests.", retryAfterS: wait }, true);
    }
    const matched = matchPath(route, target.path);
    if (matched === undefined) return replyFailure(res, { code: "not_found", message: "Not found." }, true);

    for (const guard of guards) {
      let verdict: GuardVerdict;
      try {
        verdict = await guard({ method: route.method, path: target.path, key: route.key, access: route.access, principal: principal ?? null, host });
      } catch {
        // A guard that breaks refuses: the safe direction.
        verdict = { code: "internal", message: "A safety check failed, so the request was refused." };
      }
      if (verdict !== undefined) return replyFailure(res, verdict, true);
    }

    // The body. GET and DELETE carry none.
    let rawBody: Buffer = Buffer.alloc(0);
    let parsed: unknown;
    if (route.method === "POST") {
      if (!isJsonContentType(req.headers["content-type"])) return replyFailure(res, { code: "unsupported_media_type", message: "POST bodies must be application/json." }, true);
      const declared = req.headers["content-length"];
      if (declared !== undefined) {
        if (!/^\d{1,12}$/.test(declared)) return replyFailure(res, failures.malformed(), true);
        if (Number(declared) > maxBody) return replyFailure(res, { code: "body_too_large", message: "The request body is too large." }, true);
      }
      const read = await readBody(req);
      if (read === "too_large") return replyFailure(res, { code: "body_too_large", message: "The request body is too large." }, true);
      if (read === "aborted") return void res.destroy();
      rawBody = read;
      if (route.body !== "raw") {
        let value: unknown;
        try {
          value = JSON.parse(rawBody.toString("utf8"));
        } catch {
          return replyFailure(res, { code: "invalid_request", message: "The body is not valid JSON." });
        }
        const schema = route.body;
        const checked = schema === undefined ? undefined : schema.safeParse(value);
        if (checked === undefined || !checked.success) {
          // The field path only: never the value, which could be a token or a code.
          const field = checked === undefined ? "" : (checked.error.issues[0]?.path.join(".") ?? "").slice(0, 60);
          host.emitAudit({ ev: "schema.violation", route: `POST ${target.path}`.slice(0, 64), ...(/^[A-Za-z0-9_.-]*$/.test(field) && field !== "" ? { field } : {}) });
          return replyFailure(res, { code: "invalid_request", message: "The request body does not match this route's schema.", ...(field === "" ? {} : { details: { field } }) });
        }
        parsed = checked.data;
      }
    } else if (req.headers["content-length"] !== undefined && req.headers["content-length"] !== "0") {
      return replyFailure(res, failures.malformed(), true);
    } else if (req.headers["transfer-encoding"] !== undefined) {
      return replyFailure(res, failures.malformed(), true);
    }

    const requestSignal = new AbortController();
    const onShutdown = (): void => requestSignal.abort();
    shutdown.signal.addEventListener("abort", onShutdown, { once: true });
    res.once("close", () => {
      shutdown.signal.removeEventListener("abort", onShutdown);
      requestSignal.abort();
    });
    const ctx: RouteContext<unknown> = {
      method: route.method,
      path: target.path,
      query: target.query,
      params: matched.params,
      rest: matched.rest,
      headers,
      principal: principal ?? null,
      body: parsed,
      rawBody,
      signal: requestSignal.signal,
      host,
      toWebRequest: () =>
        new Request(`${expectedOrigin(portValue)}${target.path}${target.query === "" ? "" : `?${target.query}`}`, {
          method: route.method,
          headers,
          ...(route.method === "POST" ? { body: Uint8Array.from(rawBody) } : {}),
          signal: requestSignal.signal,
        }),
    };
    let result: RouteResult;
    try {
      result = await route.handler(ctx);
    } catch (error) {
      if (error instanceof BridgeHttpError) return replyFailure(res, error.failure);
      // The class of the problem only: a message could quote a request.
      options.stderr.write(`xo-market cockpit: a handler failed (${route.key}, ${error instanceof Error ? error.name : "unknown"})\n`);
      return replyFailure(res, { code: "internal", message: "The daemon could not complete this request." });
    }
    await sendResult(res, result, requestSignal);
  }

  const server: Server = createServer({ maxHeaderSize: 16 * 1024, requestTimeout: 30_000, headersTimeout: 10_000, keepAliveTimeout: 5_000 }, (req, res) => {
    handle(req, res).catch((error: unknown) => {
      options.stderr.write(`xo-market cockpit: request failed (${error instanceof Error ? error.name : "unknown"})\n`);
      if (!res.headersSent) {
        try {
          replyFailure(res, { code: "internal", message: "The daemon could not complete this request." }, true);
        } catch {
          res.destroy();
        }
      } else {
        res.destroy();
      }
    });
  });
  server.maxConnections = 128;
  server.on("connection", (socket) => {
    sockets.add(socket);
    socket.once("close", () => sockets.delete(socket));
  });
  // No WebSocket and no tunnelling: an upgrade or CONNECT request is dropped.
  server.on("upgrade", (_req, socket) => socket.destroy());
  server.on("connect", (_req, socket) => socket.destroy());
  server.on("clientError", (_error, socket) => {
    // A connection that was already answered and told to close gets no second answer: the bytes the parser rejected
    // are the unread body of the request that was refused.
    if (answeredAndClosing.has(socket)) {
      socket.destroy();
      return;
    }
    if (socket.writable) socket.end("HTTP/1.1 400 Bad Request\r\nConnection: close\r\nContent-Length: 0\r\n\r\n");
    else socket.destroy();
  });

  await new Promise<void>((resolveListening, rejectListening) => {
    server.once("error", rejectListening);
    server.listen({ host: LOOPBACK_HOST, port: options.port ?? 0 }, () => {
      server.off("error", rejectListening);
      resolveListening();
    });
  }).catch(() => {
    throw new DaemonStartError("listen_failed", "The daemon could not listen on 127.0.0.1.");
  });
  const address = server.address() as AddressInfo;
  portValue = address.port;

  async function closeAll(): Promise<void> {
    ready = false;
    // Stops accepting; the callback runs when the last connection is gone.
    const serverClosed = new Promise<void>((resolveClosed) => {
      server.close(() => resolveClosed());
    });
    shutdown.abort();
    for (const stream of [...streams]) stream.end();
    for (const { close: closeModule } of [...moduleClosers].reverse()) {
      try {
        await closeModule();
      } catch {
        // keep closing
      }
    }
    for (const callback of closers.splice(0)) {
      try {
        await callback();
      } catch {
        // keep closing
      }
    }
    // Idle keep-alive sockets go now; a request still running gets a short grace.
    server.closeIdleConnections();
    let timer: NodeJS.Timeout | undefined;
    await Promise.race([
      serverClosed,
      new Promise<void>((resolveGrace) => {
        timer = setTimeout(() => {
          for (const socket of sockets) socket.destroy();
          resolveGrace();
        }, 1_500);
        timer.unref();
      }),
    ]);
    if (timer !== undefined) clearTimeout(timer);
    auth.wipe();
    buckets.clear();
    auditListeners.clear();
  }
  const close = (): Promise<void> => (closing ??= closeAll());

  try {
    for (const entry of options.modules ?? []) {
      let loaded: BridgeModule;
      try {
        loaded = typeof entry.source === "function" ? await entry.source(host) : entry.source;
      } catch {
        throw new DaemonStartError("module_failed", `The module ${entry.name} could not start.`, entry.name);
      }
      for (const route of loaded.routes ?? []) registerRoute(route, entry.name);
      if (loaded.close !== undefined) moduleClosers.push({ name: loaded.name, close: () => loaded.close?.() });
    }
  } catch (error) {
    await close().catch(() => undefined);
    throw error;
  }
  ready = true;

  return {
    host,
    port: portValue,
    origin: expectedOrigin(portValue),
    url: `${expectedOrigin(portValue)}/`,
    announcePairing: (opts) => announce(opts?.force === true),
    close,
  };
}

