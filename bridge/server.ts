// The Cockpit daemon's HTTP front (docs/dapp-design.md sections 1.3, 5.4, 7.2 M1-1 to M1-4, M1-8; note 27 5.3).
//
// WHAT THIS FILE IS. The transport and its guards, and a small registry the other bridge streams plug into.
// It serves the static app, mints and checks tokens, pairs the page, and for every other route calls a
// handler that a route module registered. It contains no read proxy, no tool table, no ARM window, no SSE
// feed and no inbox: those are modules (see "Writing a route module" below).
//
// WHAT IT ENFORCES, in this order, on every request (each is a test in bridge/test/server):
//   1. the request target is origin-form with no encoded slash/dot/backslash and no dot segment (400);
//   2. no duplicated Host, Origin, Authorization, Content-Type, Content-Length or Transfer-Encoding (400);
//   3. Host is exactly `127.0.0.1:<port>` (403 host_forbidden, DNS rebinding);
//   4. Origin, when present, is exactly `http://127.0.0.1:<port>` (403 origin_forbidden); on API routes
//      Sec-Fetch-Site must also be same-origin, none or absent;
//   5. only GET/HEAD for static files, GET/POST/DELETE for API routes; everything else 405 (a CORS preflight
//      never gets an approving answer: there is no Access-Control-* header anywhere);
//   6. API routes need `Authorization: Bearer <token>` (401), a scope that covers the route (403 scope_denied),
//      a passing rate limit (429) and every registered guard; only then is the body read;
//   7. POST bodies must be `application/json`, at most MAX_REQUEST_BODY_BYTES (415, 413), parsed and, when the
//      route declares a schema, validated with it (400 invalid_request).
// Responses never carry Set-Cookie or Access-Control-*; every response carries the Cockpit security headers
// (CSP and the rest, from app/headers.config.ts) and Cache-Control: no-store. Error bodies are always
// { error: { code, message, details? } } with a code from bridge/contract.ts and a fixed message.
//
// WRITING A ROUTE MODULE (D2 to D6). Export `bridgeModule` from your file (a factory `(host) => BridgeModule`,
// or the module object itself). bridge/main.ts imports these files if they exist: proxy, tool-classes, arming,
// kill, events, inbox, audit-adapter, paybox-signer. Do not edit this file or main.ts. A module is
//
//   { name, routes: readonly RouteSpec[], close?() }
//
// A route is declared with `defineRoute({ method, path, access, body?, handler })`:
//   - `path` must be one of the contract's route keys (UI_ROUTE_KEYS) or an MCP_PATH method; a trailing "/" is
//     a prefix route ("/ui/read/" is `GET /ui/read/*`); ":name" segments are captured in ctx.params;
//   - `access` is required: "public" (no token; only /ui/pair uses it) or { scope } (the token must hold that
//     scope; every token holds "read"). `kinds` can restrict to ui or agent tokens. Which scope a route or tool
//     needs is the class table's decision (bridge/tool-classes.ts), not this file's;
//   - POST routes must declare `body`: a zod schema (ctx.body is its output) or "raw" (ctx.rawBody only);
//   - the handler returns json(...), fail(...), a stream (SSE) or a Web Response (for createMcpHandler), or
//     throws BridgeHttpError. Any other throw becomes a fixed 500 internal answer that quotes nothing.
// Cross-cutting checks (the ARM window for submit, the kill switch) are guards: `host.addGuard(fn)`; a guard
// runs after the scope check and before the body is read. `host.emitAudit(record)` hands an external audit
// event to whichever sink the audit adapter attached (events before that are replayed to it).
//
// Nothing here writes to stdout; operator output goes to host.stderr.

export type HttpMethod = "GET" | "POST" | "DELETE";
export type RouteAccess = "public" | { readonly scope: TokenScope };

export interface RouteContext<B = unknown> {
  readonly method: HttpMethod;
  // The raw path as sent (no query, escapes not decoded) and the raw query without "?".
  readonly path: string;
  readonly query: string;
  // ":name" captures of a pattern route; empty otherwise. For a prefix route, `rest` is the part after it.
  readonly params: Readonly<Record<string, string>>;
  readonly rest: string;
  // Lower-case names, single values. Authorization and Cookie are removed: a module cannot forward them.
  readonly headers: Readonly<Record<string, string>>;
  // null only on a "public" route.
  readonly principal: Principal | null;
  readonly body: B;
  readonly rawBody: Uint8Array;
  // Aborts when the client disconnects or the daemon shuts down.
  readonly signal: AbortSignal;
  readonly host: DaemonHost;
  // The request as a Web Request (sanitised headers, the buffered body), for createMcpHandler.
  toWebRequest(): Request;
}

export interface StreamSink {
  // False when the socket buffer is full (wait for onDrain) or the stream is closed.
  write(chunk: string): boolean;
  onDrain(callback: () => void): void;
  // Runs once when the client goes away, the module ends the stream, or the daemon shuts down.
  onClose(callback: () => void): void;
  end(): void;
  readonly closed: boolean;
}

export interface JsonResult {
  readonly kind: "json";
  readonly status: number;
  readonly body: unknown;
  readonly headers?: Readonly<Record<string, string>>;
}
export interface StreamResult {
  readonly kind: "stream";
  readonly status?: number;
  readonly contentType: string;
  // Called once the headers are on the wire. The stream ends when the module calls sink.end() or it closes.
  start(sink: StreamSink): void | Promise<void>;
}
export interface WebResult {
  readonly kind: "web";
  readonly response: Response;
}
export type RouteResult = JsonResult | StreamResult | WebResult;

export interface RouteSpec<B = unknown> {
  readonly method: HttpMethod;
  readonly path: string;
  readonly access: RouteAccess;
  // Default both. A route that only the page (or only the agent) should call can say so.
  readonly kinds?: readonly TokenKind[];
  readonly body?: z.ZodType<B> | "raw";
  readonly handler: (ctx: RouteContext<B>) => RouteResult | Promise<RouteResult>;
}

// A RouteSpec with its body type erased; what the registry stores.
export interface RegisteredRoute {
  readonly method: HttpMethod;
  readonly path: string;
  readonly key: string;
  readonly access: RouteAccess;
  readonly kinds: readonly TokenKind[];
  readonly body: z.ZodType | "raw" | undefined;
  readonly handler: (ctx: RouteContext<unknown>) => RouteResult | Promise<RouteResult>;
}

export function defineRoute<B = unknown>(spec: RouteSpec<B>): RegisteredRoute {
  return {
    method: spec.method,
    path: spec.path,
    key: routeKeyOf(spec.method, spec.path),
    access: spec.access,
    kinds: spec.kinds ?? ["ui", "agent"],
    body: spec.body,
    // The body was parsed by the same schema the route declared, so the cast restates what was checked.
    handler: (ctx) => spec.handler(ctx as RouteContext<B>),
  };
}

export function routeKeyOf(method: HttpMethod, path: string): string {
  return path.endsWith("/") ? `${method} ${path}*` : `${method} ${path}`;
}

export interface BridgeModule {
  readonly name: string;
  readonly routes?: readonly RegisteredRoute[];
  // Called at shutdown, after open streams were ended, in reverse order of registration.
  close?(): void | Promise<void>;
}
export type BridgeModuleFactory = (host: DaemonHost) => BridgeModule | Promise<BridgeModule>;
export type BridgeModuleSource = BridgeModule | BridgeModuleFactory;

// ---- errors and results --------------------------------------------------------------------------------------------

export interface FailureBody {
  readonly code: BridgeErrorCode;
  readonly message: string;
  readonly details?: Readonly<Record<string, string | number | boolean | null | readonly string[]>>;
  readonly retryAfterS?: number;
}

export class BridgeHttpError extends Error {
  readonly failure: FailureBody;
  constructor(code: BridgeErrorCode, message: string, extra: { readonly details?: FailureBody["details"]; readonly retryAfterS?: number } = {}) {
    super(code);
    this.name = "BridgeHttpError";
    this.failure = { code, message, ...extra };
  }
}

export function json(body: unknown, status = 200, headers?: Readonly<Record<string, string>>): JsonResult {
  return { kind: "json", status, body, ...(headers === undefined ? {} : { headers }) };
}

export function errorBody(failure: FailureBody): { readonly error: Record<string, unknown> } {
  return {
    error: {
      code: failure.code,
      // The message is fixed daemon text; cap it so a careless caller cannot push a large upstream body through.
      message: failure.message.slice(0, 500),
      ...(failure.details === undefined ? {} : { details: failure.details }),
      ...(failure.retryAfterS === undefined ? {} : { retry_after_s: Math.max(0, Math.min(86_400, Math.floor(failure.retryAfterS))) }),
    },
  };
}

export function fail(code: BridgeErrorCode, message: string, extra: { readonly details?: FailureBody["details"]; readonly retryAfterS?: number } = {}): JsonResult {
  const failure: FailureBody = { code, message, ...extra };
  return json(errorBody(failure), BRIDGE_ERROR_HTTP_STATUS[code], failure.retryAfterS === undefined ? undefined : { "Retry-After": String(Math.max(0, Math.floor(failure.retryAfterS))) });
}

